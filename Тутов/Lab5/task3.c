#include <stdio.h>
#include <locale.h>

int main() {
    setlocale(LC_ALL, "Ukrainian");

    int num;
    printf("Введіть тризначне число (від 100 до 999): ");
    scanf("%d", &num);

    if (num < 100 || num > 999) {
        printf("Помилка: введене число не є тризначним!\n");
        return 0;
    }

    int h = num / 100;          // Сотні
    int t = (num / 10) % 10;    // Десятки
    int u = num % 10;           // Одиниці

    // Масиви рядків 
    const char* h_words[] = {"", "сто", "двісті", "триста", "чотириста", "п'ятсот", "шістьсот", "сімсот", "вісімсот", "дев'ятсот"};
    const char* t_words[] = {"", "", "двадцять", "тридцять", "сорок", "п'ятдесят", "шістдесят", "сімдесят", "вісімдесят", "дев'яносто"};
    const char* teens_words[] = {"десять", "одинадцять", "дванадцять", "тринадцять", "чотирнадцять", "п'ятнадцять", "шістнадцять", "сімнадцять", "вісімнадцять", "дев'ятнадцять"};
    const char* u_words[] = {"", "один", "два", "три", "чотири", "п'ять", "шість", "сім", "вісім", "дев'ять"};

    printf("Число прописом: ");
    
    // Виводимо сотні
    printf("%s ", h_words[h]);

    // Виводимо десятки та одиниці
    if (t == 1) {
        printf("%s\n", teens_words[u]);
    } else {
        if (t > 1) {
            printf("%s ", t_words[t]);
        }
        if (u > 0) {
            printf("%s\n", u_words[u]);
        } else {
            printf("\n");
        }
    }

    return 0;
}
